    execute format('drop policy if exists %1$s_sel on public.%1$s; create policy %1$s_sel on public.%1$s for select to authenticated using (public.is_aprovado());', t);
    execute format('drop policy if exists %1$s_ins on public.%1$s; create policy %1$s_ins on public.%1$s for insert to authenticated with check (public.is_admin());', t);
    execute format('drop policy if exists %1$s_upd on public.%1$s; create policy %1$s_upd on public.%1$s for update to authenticated using (public.is_admin()) with check (public.is_admin());', t);
    execute format('revoke all on public.%1$s from anon;', t);
  end loop;
end $$;
