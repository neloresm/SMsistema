-- ---------------------------------------------------------------------
-- Conferência automática (central de revisão)
-- ---------------------------------------------------------------------
create or replace function public.rcb_conferir_contrato(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
  c record; v_soma numeric; v_diff numeric; v_zero int; v_modal numeric; v_enc numeric; v_res numeric;
  v_qtd int; v_pagas int; v_num_origem int; v_den_origem int; v_txt text; v_pct numeric;
  v_email text; v_ldata date;
begin
  if auth.uid() is not null and not public.is_admin() then raise exception 'Sem permissão'; end if;
  select * into c from rcb_contratos where id = p_id;
  if not found then return; end if;

  -- remove itens automáticos não resolvidos (serão recalculados)
  delete from rcb_revisao_itens where contrato_id = p_id and not resolvido and codigo <> 'MANUAL';

  create temp table if not exists _novos (sev text, cod text, msg text) on commit drop;
  delete from _novos;

  select coalesce(sum(valor_previsto),0), count(*) filter (where liquidacao_externa and valor_previsto = 0), count(*)
    into v_soma, v_zero, v_qtd
    from rcb_parcelas where contrato_id = p_id and not cancelada;
  select mode() within group (order by valor_previsto) into v_modal
    from rcb_parcelas where contrato_id = p_id and not cancelada and valor_previsto > 0;
  v_modal := coalesce(v_modal, 0);
  -- encargos/variações já pagas acima do valor padrão (multa/juros embutidos na baixa)
  select coalesce(sum(greatest(p.valor_previsto - v_modal, 0)),0) into v_enc
    from rcb_parcelas p where p.contrato_id = p_id and not p.cancelada and p.valor_previsto > 0
     and p.valor_previsto <> v_modal
     and exists (select 1 from rcb_pagamentos g where g.parcela_id = p.id and not g.estornado);

  v_diff := c.valor_total - v_soma;
  if abs(v_diff) >= 0.05 then
    v_res := v_diff - v_zero * v_modal + v_enc;
    if v_zero > 0 and abs(v_res) <= 0.20 then
      insert into _novos values ('info','FORA_PLATAFORMA',
        format('%s parcela(s) consta(m) como liquidada(s) fora da plataforma (no cadastro ou direto ao vendedor) sem valor registrado. A diferença de R$ %s entre o valor do contrato e a soma das parcelas equivale a %s × R$ %s%s. Data e valor reais desses recebimentos não estão comprovados.',
          v_zero, public.rcb_brl(v_diff), v_zero, public.rcb_brl(v_modal),
          case when v_enc <> 0 then format(' (descontados R$ %s de encargos/variações embutidos em parcelas pagas)', public.rcb_brl(v_enc)) else '' end));
    elsif abs(v_res) <= c.valor_total * 0.02 then
      insert into _novos values ('atencao','DIFERENCA_VALOR',
        format('Soma das parcelas (R$ %s) difere do valor do contrato (R$ %s) em R$ %s; %s parcela(s) sem valor registrado (padrão R$ %s). Resíduo não explicado: R$ %s.',
          public.rcb_brl(v_soma), public.rcb_brl(c.valor_total), public.rcb_brl(v_diff),
          v_zero, public.rcb_brl(v_modal), public.rcb_brl(v_res)));
    else
      insert into _novos values ('critico','DIFERENCA_VALOR',
        format('Soma das parcelas (R$ %s) não corresponde ao valor do contrato (R$ %s). Diferença: R$ %s.',
          public.rcb_brl(v_soma), public.rcb_brl(c.valor_total), public.rcb_brl(v_diff)));
    end if;
  end if;

  if c.qtd_parcelas is not null and c.qtd_parcelas <> v_qtd then
    insert into _novos values ('critico','QTD_PARCELAS', format('Contrato indica %s parcelas, mas há %s cadastradas.', c.qtd_parcelas, v_qtd));
  end if;

  if c.pagto_origem ~ '^\d+/\d+$' then
    v_num_origem := split_part(c.pagto_origem,'/',1)::int;
    select count(*) into v_pagas from rcb_parcelas p where p.contrato_id = p_id and not p.cancelada
      and (p.liquidacao_externa or exists (select 1 from rcb_pagamentos g where g.parcela_id = p.id and not g.estornado));
    if v_pagas <> v_num_origem then
      insert into _novos values ('atencao','PAGTO_ORIGEM', format('Sistema de origem indica %s parcela(s) paga(s); aqui constam %s.', v_num_origem, v_pagas));
    end if;
  end if;

  -- parcela posterior quitada enquanto anterior segue em atraso
  select string_agg(format('parcela %s (venc. %s) em aberto, mas parcela %s (venc. %s) quitada em %s', a.numero, to_char(a.vencimento,'DD/MM/YYYY'), b.numero, to_char(b.vencimento,'DD/MM/YYYY'), to_char(g.data_pagamento,'DD/MM/YYYY')), '; ')
    into v_txt
    from rcb_parcelas a
    join rcb_parcelas b on b.contrato_id = a.contrato_id and b.vencimento > a.vencimento and not b.cancelada
    join rcb_pagamentos g on g.parcela_id = b.id and not g.estornado
   where a.contrato_id = p_id and not a.cancelada and a.valor_previsto > 0 and a.vencimento < public.rcb_hoje()
     and coalesce((select sum(valor) from rcb_pagamentos x where x.parcela_id = a.id and not x.estornado),0) < a.valor_previsto
     and g.data_pagamento >= a.vencimento;
  if v_txt is not null then
    insert into _novos values ('atencao','ALOCACAO', 'Conferir alocação do pagamento: ' || v_txt || '. O valor pode ter sido baixado na parcela errada.');
  end if;

  select string_agg(format('%s (%s)', p.numero, to_char(p.vencimento,'DD/MM/YYYY')), ', ' order by p.numero) into v_txt
    from rcb_parcelas p
   where p.contrato_id = p_id and not p.cancelada
     and exists (select 1 from rcb_parcelas q where q.contrato_id = p.contrato_id and not q.cancelada and q.numero < p.numero and q.vencimento > p.vencimento);
  if v_txt is not null then
    insert into _novos values ('info','VENC_FORA_ORDEM', 'Parcelas com vencimento fora da ordem numérica: ' || v_txt || '. Possível antecipação/reorganização no sistema de origem.');
  end if;

  select string_agg(format('%s: R$ %s', p.numero, public.rcb_brl(p.valor_previsto)), '; ' order by p.numero) into v_txt
    from rcb_parcelas p
   where p.contrato_id = p_id and not p.cancelada and p.valor_previsto > 0 and abs(p.valor_previsto - v_modal) >= 0.05;
  if v_txt is not null then
    insert into _novos values ('info','VALOR_DIVERGENTE', format('Parcelas com valor diferente do padrão (R$ %s): %s. Em parcelas já pagas, a diferença costuma ser encargo de atraso ou desconto.', public.rcb_brl(v_modal), v_txt));
  end if;

  select email into v_email from rcb_compradores where id = c.comprador_id;
  if v_email is null or v_email ~* '^(no)?complemento_?|sememail|nocomplemento' then
    insert into _novos values ('atencao','EMAIL_INVALIDO', format('E-mail do comprador parece ser provisório/inválido: %s.', coalesce(v_email,'(vazio)')));
  end if;

  select data into v_ldata from rcb_leiloes where id = c.leilao_id;
  if c.data_contrato is not null and v_ldata is not null and (c.data_contrato < v_ldata or c.data_contrato - v_ldata > 60) then
    insert into _novos values ('info','DATA_CONTRATO', format('Data do contrato (%s) distante da data do leilão (%s). Pode indicar reemissão, revenda de participação ou renegociação.', to_char(c.data_contrato,'DD/MM/YYYY'), to_char(v_ldata,'DD/MM/YYYY')));
  end if;

  -- participações no mesmo lote
  if c.lote is not null then
    select sum(percentual), string_agg(format('%s (%s%%)', id, replace(trim(to_char(percentual,'FM990.00')),'.',',')), ', ' order by id) into v_pct, v_txt
      from rcb_contratos x where x.leilao_id = c.leilao_id and upper(x.lote) = upper(c.lote) and not x.arquivado;
    if v_pct > 100.01 then
      insert into _novos values ('critico','LOTE_EXCEDE_100', format('Soma das participações vendidas no lote %s deste leilão = %s%% (contratos %s). Possível duplicidade ou renegociação.', c.lote, replace(trim(to_char(v_pct,'FM990.00')),'.',','), v_txt));
    end if;
    select string_agg(x.id::text, ', ') into v_txt from rcb_contratos x
     where x.id <> c.id and x.leilao_id = c.leilao_id and upper(x.lote) = upper(c.lote) and x.comprador_id = c.comprador_id and not x.arquivado;
    if v_txt is not null then
      insert into _novos values ('critico','DUPLICIDADE', format('Mesmo comprador e mesmo lote em outro(s) contrato(s): %s. Confirmar se é duplicidade, substituição ou renegociação antes de consolidar.', v_txt));
    end if;
  end if;

  if c.assinatura = 'sem_assinatura' then
    insert into _novos values ('info','SEM_ASSINATURA', 'Documento anexado no sistema de origem é "contrato sem assinatura".');
  end if;
  if c.tipo_venda = 'nao_identificado' then
    insert into _novos values ('info','TIPO_NAO_IDENTIFICADO', 'Tipo de venda (animal, prenhez, aspiração…) não consta na descrição.');
  end if;

  insert into rcb_revisao_itens (contrato_id, severidade, codigo, mensagem)
  select p_id, n.sev, n.cod, n.msg from _novos n
   where not exists (select 1 from rcb_revisao_itens r where r.contrato_id = p_id and r.codigo = n.cod and r.resolvido);

  if exists (select 1 from rcb_revisao_itens r where r.contrato_id = p_id and not r.resolvido and r.severidade in ('critico','atencao')) then
    update rcb_contratos set revisao_status = 'pendente' where id = p_id and revisao_status <> 'pendente';
  end if;
end $$;

create or replace function public.rcb_conferir_todos() returns int
language plpgsql security definer set search_path = public as $$
declare r record; n int := 0;
begin
  if auth.uid() is not null and not public.is_admin() then raise exception 'Sem permissão'; end if;
  for r in select id from rcb_contratos where not arquivado loop
    perform public.rcb_conferir_contrato(r.id); n := n + 1;
  end loop;
  return n;
end $$;

-- ---------------------------------------------------------------------
-- Importação (usada pelo seed, pelo importador e pelo cadastro manual)
-- ---------------------------------------------------------------------
create or replace function public.rcb_importar_contrato(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_leilao bigint; v_comp bigint; v_id bigint; r jsonb; v_parc bigint; v_doc text; x record;
begin
  if auth.uid() is not null and not public.is_admin() then
    raise exception 'Apenas administradores podem cadastrar contratos.';
  end if;
  if coalesce(p#>>'{leilao,nome}','') = '' then raise exception 'Leilão não informado.'; end if;
  if coalesce(p#>>'{comprador,nome}','') = '' then raise exception 'Comprador não informado.'; end if;
  if (p->>'valor_total') is null then raise exception 'Valor total não informado.'; end if;

  if (p->>'id') is not null and exists (select 1 from rcb_contratos where id = (p->>'id')::bigint) then
    raise exception 'Contrato % já está cadastrado (duplicado).', p->>'id';
  end if;

  select id into v_leilao from rcb_leiloes
   where nome = p#>>'{leilao,nome}' and data is not distinct from nullif(p#>>'{leilao,data}','')::date;
  if v_leilao is null then
    insert into rcb_leiloes (nome, data, local)
    values (p#>>'{leilao,nome}', nullif(p#>>'{leilao,data}','')::date, nullif(p#>>'{leilao,local}',''))
    returning id into v_leilao;
  end if;

  v_doc := nullif(regexp_replace(coalesce(p#>>'{comprador,documento}',''), '\D', '', 'g'), '');
  if v_doc is not null then select id into v_comp from rcb_compradores where documento = v_doc; end if;
  if v_comp is null then
    insert into rcb_compradores (nome, documento, email, telefone)
    values (p#>>'{comprador,nome}', v_doc, nullif(p#>>'{comprador,email}',''), nullif(p#>>'{comprador,telefone}',''))
    returning id into v_comp;
  end if;

  insert into rcb_contratos (id, leilao_id, comprador_id, descricao, animal, acasalamento, tipo_venda, percentual, lote,
                         data_contrato, valor_total, qtd_parcelas, pagto_origem, vendedor, condicoes, assinatura,
                         documentos_origem, ultima_ocorrencia, fonte, revisao_status, obs)
  values (coalesce((p->>'id')::bigint, nextval('public.rcb_contratos_manual_seq')), v_leilao, v_comp,
          p->>'descricao', nullif(p->>'animal',''), nullif(p->>'acasalamento',''),
          coalesce(nullif(p->>'tipo_venda',''),'nao_identificado'), nullif(p->>'percentual','')::numeric, nullif(p->>'lote',''),
          nullif(p->>'data_contrato','')::date, (p->>'valor_total')::numeric, nullif(p->>'qtd_parcelas','')::int,
          nullif(p->>'pagto_origem',''), nullif(p->>'vendedor',''), nullif(p->>'condicoes',''),
          coalesce(nullif(p->>'assinatura',''),'nao_informado'),
          coalesce((select array_agg(value) from jsonb_array_elements_text(p->'documentos_origem')), '{}'),
          p->'ultima_ocorrencia', coalesce(nullif(p->>'fonte',''),'manual'), 'pendente', nullif(p->>'obs',''))
  returning id into v_id;

  for r in select value from jsonb_array_elements(coalesce(p->'parcelas','[]'::jsonb)) loop
    insert into rcb_parcelas (contrato_id, numero, vencimento, valor_previsto, status_origem, liquidacao_externa, data_liquidacao_externa, tipo)
    values (v_id, (r->>'numero')::int, (r->>'vencimento')::date, (r->>'valor_previsto')::numeric,
            nullif(r->>'status_origem',''), coalesce((r->>'liquidacao_externa')::boolean,false),
            nullif(r->>'data_liquidacao_externa','')::date,
            public.rcb_tipo_parcela((r->>'numero')::int, (r->>'liquidacao_externa')::boolean, r->>'status_origem', r->>'tipo'))
    returning id into v_parc;
    if r ? 'pagamento' and coalesce((r#>>'{pagamento,valor}')::numeric,0) > 0 then
      insert into rcb_pagamentos (parcela_id, data_pagamento, valor, forma, obs, origem)
      values (v_parc, (r#>>'{pagamento,data}')::date, (r#>>'{pagamento,valor}')::numeric,
              nullif(r#>>'{pagamento,forma}',''), coalesce(r#>>'{pagamento,obs}','Baixa importada do sistema de cobrança'), 'importacao');
    end if;
  end loop;

  for r in select value from jsonb_array_elements(coalesce(p->'revisao','[]'::jsonb)) loop
    insert into rcb_revisao_itens (contrato_id, severidade, codigo, mensagem)
    values (v_id, coalesce(r->>'severidade','atencao'), 'MANUAL', r->>'mensagem');
  end loop;

  perform public.rcb_conferir_contrato(v_id);
  -- reconfere rcb_contratos do mesmo lote (participações cruzadas)
  for x in select id from rcb_contratos c2 where c2.id <> v_id and c2.leilao_id = v_leilao
           and upper(coalesce(c2.lote,'')) = upper(coalesce(p->>'lote','#')) loop
    perform public.rcb_conferir_contrato(x.id);
  end loop;

  if p->>'revisao_status_se_ok' = 'aprovado'
     and not exists (select 1 from rcb_revisao_itens where contrato_id = v_id and not resolvido and severidade in ('critico','atencao')) then
    update rcb_contratos set revisao_status = 'aprovado', revisado_em = now() where id = v_id;
  end if;
  return v_id;
end $$;

