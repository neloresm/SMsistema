create table if not exists public.rcb_leiloes (
  id bigint generated by default as identity primary key,
  nome text not null,
  data date,
  local text,
  created_at timestamptz not null default now(),
  unique (nome, data)
);

create table if not exists public.rcb_compradores (
  id bigint generated by default as identity primary key,
  nome text not null,
  documento text unique,           -- CPF/CNPJ só dígitos
  email text,
  telefone text,
  obs text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create sequence if not exists public.rcb_contratos_manual_seq start 900000;

create table if not exists public.rcb_contratos (
  id bigint primary key default nextval('public.rcb_contratos_manual_seq'), -- nº do contrato
  leilao_id bigint not null references public.rcb_leiloes(id),
  comprador_id bigint not null references public.rcb_compradores(id),
  descricao text not null,
  animal text,
  acasalamento text,
  tipo_venda text not null default 'nao_identificado'
    check (tipo_venda in ('animal','prenhez','aspiracao','embriao','participacao','outro','nao_identificado')),
  percentual numeric(7,4),          -- % comercializado
  lote text,
  data_contrato date,
  valor_total numeric(14,2) not null check (valor_total >= 0),
  participacao_sm_pct numeric(7,4) check (participacao_sm_pct is null or (participacao_sm_pct > 0 and participacao_sm_pct <= 100)),
  qtd_parcelas int,
  pagto_origem text,                -- ex.: "4/30" exibido no sistema de cobrança
  vendedor text,
  condicoes text,                   -- entrada, comissões, taxas, descontos, etc.
  assinatura text not null default 'nao_informado' check (assinatura in ('assinado','sem_assinatura','nao_informado')),
  documentos_origem text[] not null default '{}',
  ultima_ocorrencia jsonb,
  fonte text not null default 'manual',
  revisao_status text not null default 'pendente' check (revisao_status in ('pendente','aprovado')),
  revisado_por uuid,
  revisado_em timestamptz,
  arquivado boolean not null default false,
  arquivado_motivo text,
  obs text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists contratos_leilao_idx on public.rcb_contratos(leilao_id);
create index if not exists contratos_comprador_idx on public.rcb_contratos(comprador_id);

create table if not exists public.rcb_parcelas (
  id bigint generated by default as identity primary key,
  contrato_id bigint not null references public.rcb_contratos(id),
  numero int not null check (numero > 0),
  vencimento date not null,
  valor_previsto numeric(14,2) not null check (valor_previsto >= 0),
  status_origem text,               -- texto original (ex.: "Liquidada no cadastro em 01/10/2026")
  liquidacao_externa boolean not null default false, -- liquidada fora da plataforma, sem valor registrado
  data_liquidacao_externa date,
  cancelada boolean not null default false,
  cancelada_motivo text,
  obs text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (contrato_id, numero)
);
create index if not exists parcelas_venc_idx on public.rcb_parcelas(vencimento);

create table if not exists public.rcb_pagamentos (
