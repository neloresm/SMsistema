-- ---------------------------------------------------------------------
-- Tipo de parcela: só as parcelas "mecob" entram na conferência do repasse
--   entrada  = parcela 1 (vai direto para a SM)
--   cadastro = "Liquidada no cadastro"
--   direto   = paga direto ao vendedor (liquidada sem valor no sistema de cobrança)
--   mecob    = cobrada e repassada pela MECOB
-- ---------------------------------------------------------------------
alter table public.rcb_parcelas add column if not exists tipo text not null default 'mecob'
  check (tipo in ('entrada','mecob','direto','cadastro'));

create or replace function public.rcb_tipo_parcela(p_numero int, p_liq_externa boolean, p_status text, p_tipo text)
returns text language sql immutable as $$
  select case
    when coalesce(p_tipo,'') in ('entrada','mecob','direto','cadastro') then p_tipo
    when p_numero = 1 then 'entrada'
    when coalesce(p_status,'') ilike 'Liquidada no cadastro%' then 'cadastro'
    when coalesce(p_liq_externa,false) then 'direto'
    else 'mecob' end
$$;

