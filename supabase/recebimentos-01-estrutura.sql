-- ---------------------------------------------------------------------
-- Triggers: updated_at, auditoria, bloqueio de exclusão, regras de pagamento
-- ---------------------------------------------------------------------
create or replace function public.rcb_tg_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;

create or replace function public.rcb_tg_audit() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_id text;
begin
  if tg_op = 'DELETE' then v_id := old.id::text; else v_id := new.id::text; end if;
  insert into public.rcb_audit_log (tabela, registro_id, acao, antes, depois, usuario, usuario_email)
  values (tg_table_name, v_id, tg_op,
          case when tg_op <> 'INSERT' then to_jsonb(old) end,
          case when tg_op <> 'DELETE' then to_jsonb(new) end,
          auth.uid(), (select email from public.profiles where id = auth.uid()));
  return coalesce(new, old);
end $$;

create or replace function public.rcb_tg_bloquear_exclusao() returns trigger language plpgsql as $$
begin
  raise exception 'Exclusão bloqueada em %. Use arquivamento, cancelamento ou estorno.', tg_table_name;
end $$;

create or replace function public.rcb_tg_pagamento_regras() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.data_pagamento > public.rcb_hoje() then
      raise exception 'Data de pagamento (%) não pode ser futura.', new.data_pagamento;
    end if;
    return new;
  end if;
  -- UPDATE: lançamentos são imutáveis; só é permitido estornar ou ajustar observação
  if old.estornado then raise exception 'Lançamento já estornado não pode ser alterado.'; end if;
  if new.valor <> old.valor or new.data_pagamento <> old.data_pagamento or new.parcela_id <> old.parcela_id then
    raise exception 'Valor, data e parcela de um lançamento não podem ser alterados. Estorne e lance novamente.';
  end if;
  if new.estornado and coalesce(trim(new.estorno_motivo),'') = '' then
    raise exception 'Informe o motivo do estorno.';
  end if;
  if new.estornado then new.estornado_em := now(); new.estornado_por := auth.uid(); end if;
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['rcb_compradores','rcb_contratos','rcb_parcelas'] loop
    execute format('drop trigger if exists %1$s_upd on public.%1$s; create trigger %1$s_upd before update on public.%1$s for each row execute function public.rcb_tg_updated_at();', t);
  end loop;
  foreach t in array array['rcb_leiloes','rcb_compradores','rcb_contratos','rcb_parcelas','rcb_pagamentos','rcb_anexos','rcb_revisao_itens'] loop
    execute format('drop trigger if exists %1$s_audit on public.%1$s; create trigger %1$s_audit after insert or update or delete on public.%1$s for each row execute function public.rcb_tg_audit();', t);
  end loop;
  foreach t in array array['rcb_leiloes','rcb_compradores','rcb_contratos','rcb_parcelas','rcb_pagamentos','rcb_anexos','rcb_audit_log'] loop
    execute format('drop trigger if exists %1$s_nodel on public.%1$s; create trigger %1$s_nodel before delete on public.%1$s for each row execute function public.rcb_tg_bloquear_exclusao();', t);
  end loop;
end $$;

