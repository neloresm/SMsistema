create or replace function public.rcb_hoje() returns date
language sql stable as $$ select (now() at time zone 'America/Sao_Paulo')::date $$;

create or replace function public.rcb_brl(v numeric) returns text
language sql immutable as $$ select translate(to_char(v,'FM999,999,990.00'), ',.', '.,') $$;

