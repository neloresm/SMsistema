-- reimportação do extrato de contratos da MECOB: atualiza o que já existe, sem duplicar
create or replace function public.rcb_atualizar_contrato(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_id bigint := (p->>'id')::bigint; r jsonb; v record; v_parc bigint; n_novas int := 0; n_pag int := 0; n_div int := 0;
begin
  if not public.is_admin() then raise exception 'Sem permissão'; end if;
  if not exists (select 1 from rcb_contratos where id = v_id) then raise exception 'Contrato % não cadastrado.', v_id; end if;
  for r in select value from jsonb_array_elements(coalesce(p->'parcelas','[]'::jsonb)) loop
    select * into v from rcb_parcelas where contrato_id = v_id and numero = (r->>'numero')::int;
    if not found then
      insert into rcb_parcelas (contrato_id, numero, vencimento, valor_previsto, status_origem, liquidacao_externa, data_liquidacao_externa, tipo)
      values (v_id, (r->>'numero')::int, (r->>'vencimento')::date, (r->>'valor_previsto')::numeric, r->>'status_origem',
              coalesce((r->>'liquidacao_externa')::boolean,false), nullif(r->>'data_liquidacao_externa','')::date,
              public.rcb_tipo_parcela((r->>'numero')::int, (r->>'liquidacao_externa')::boolean, r->>'status_origem', r->>'tipo'))
      returning id into v_parc;
      n_novas := n_novas + 1;
    else
      v_parc := v.id;
      update rcb_parcelas set status_origem = r->>'status_origem' where id = v.id and status_origem is distinct from r->>'status_origem';
      if coalesce((r->>'liquidacao_externa')::boolean,false) and not v.liquidacao_externa then
        update rcb_parcelas set liquidacao_externa = true, data_liquidacao_externa = nullif(r->>'data_liquidacao_externa','')::date,
               tipo = public.rcb_tipo_parcela(v.numero, true, r->>'status_origem', null)
         where id = v.id and valor_previsto = 0;
      end if;
      if not (r ? 'pagamento') and abs(v.valor_previsto - (r->>'valor_previsto')::numeric) >= 0.01 then n_div := n_div + 1; end if;
    end if;
    if r ? 'pagamento' and coalesce((r#>>'{pagamento,valor}')::numeric,0) > 0
       and not exists (select 1 from rcb_pagamentos g where g.parcela_id = v_parc and not g.estornado) then
      insert into rcb_pagamentos (parcela_id, data_pagamento, valor, obs, origem)
      values (v_parc, (r#>>'{pagamento,data}')::date, (r#>>'{pagamento,valor}')::numeric,
              coalesce(r#>>'{pagamento,obs}','Baixa importada do sistema de cobrança'), 'importacao');
      n_pag := n_pag + 1;
    end if;
  end loop;
  update rcb_contratos set pagto_origem = coalesce(nullif(p->>'pagto_origem',''), pagto_origem),
         ultima_ocorrencia = coalesce(p->'ultima_ocorrencia', ultima_ocorrencia),
         documentos_origem = coalesce((select array_agg(value) from jsonb_array_elements_text(p->'documentos_origem')), documentos_origem)
   where id = v_id;
  if n_div > 0 then
    insert into rcb_revisao_itens (contrato_id, severidade, codigo, mensagem)
    values (v_id, 'atencao', 'MANUAL', format('Reimportação em %s: %s parcela(s) em aberto com valor diferente do cadastrado. Conferir.', to_char(now() at time zone 'America/Sao_Paulo','DD/MM/YYYY'), n_div));
  end if;
  perform public.rcb_conferir_contrato(v_id);
  return jsonb_build_object('contrato', v_id, 'parcelas_novas', n_novas, 'pagamentos_novos', n_pag, 'valores_divergentes', n_div);
end $$;

-- ---------------------------------------------------------------------
-- RLS — leitura para usuários aprovados do SM sistema; escrita só administrador
-- (usa public.is_aprovado() e public.is_admin() que o SM sistema já possui)
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['rcb_leiloes','rcb_compradores','rcb_contratos','rcb_parcelas','rcb_pagamentos','rcb_anexos','rcb_revisao_itens','rcb_repasses','rcb_repasse_linhas','rcb_config'] loop
