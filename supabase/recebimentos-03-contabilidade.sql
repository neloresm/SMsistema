-- grava o relatório com a empresa de contabilidade
create or replace function public.rcb_salvar_repasse(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint; r jsonb; v_cred numeric := 0; v_tax numeric := 0; v_deb numeric := 0; v_contab bigint;
begin
  if not public.is_admin() then raise exception 'Apenas administradores podem enviar relatórios.'; end if;
  for r in select value from jsonb_array_elements(coalesce(p->'linhas','[]'::jsonb)) loop
    if r->>'tipo' = 'credito' then v_cred := v_cred + (r->>'valor')::numeric;
    elsif r->>'tipo' = 'taxa' then v_tax := v_tax + (r->>'valor')::numeric;
    else v_deb := v_deb + (r->>'valor')::numeric; end if;
  end loop;
  if coalesce((p->>'forcar')::boolean,false) = false and (
       abs(v_cred - coalesce((p->>'creditos')::numeric,0)) > 0.009 or abs(v_tax - coalesce((p->>'taxas')::numeric,0)) > 0.009
    or abs(v_deb - coalesce((p->>'debitos')::numeric,0)) > 0.009) then
    raise exception 'As linhas lidas (créditos %, taxas %, débitos %) não batem com o resumo do relatório. Confira o arquivo.', v_cred, v_tax, v_deb;
  end if;
  v_contab := coalesce(nullif(p->>'contabilidade_id','')::bigint, (select valor::bigint from rcb_config where chave = 'contabilidade_atual'));
  if (p->>'substitui') is not null then
    update rcb_repasses set substituido = true, obs = coalesce(obs || ' · ','') || 'Substituído por novo envio em ' || to_char(now() at time zone 'America/Sao_Paulo','DD/MM/YYYY HH24:MI')
     where id = (p->>'substitui')::bigint;
  end if;
  insert into rcb_repasses (mes, titulo, periodo_inicio, periodo_fim, creditos, debitos, taxas, valor_final, arquivo_nome, storage_path, obs, contabilidade_id)
  values (p->>'mes', p->>'titulo', nullif(p->>'periodo_inicio','')::date, nullif(p->>'periodo_fim','')::date,
          coalesce((p->>'creditos')::numeric,0), coalesce((p->>'debitos')::numeric,0), coalesce((p->>'taxas')::numeric,0),
          (p->>'valor_final')::numeric, p->>'arquivo_nome', p->>'storage_path', nullif(p->>'obs',''), v_contab)
  returning id into v_id;
  for r in select value from jsonb_array_elements(coalesce(p->'linhas','[]'::jsonb)) loop
    insert into rcb_repasse_linhas (repasse_id, tipo, contrato_id, parcelas, referencia, descricao, comprador, vencimento, data_credito, honorario, valor)
    values (v_id, r->>'tipo', nullif(r->>'contrato_id','')::bigint,
            coalesce((select array_agg(x::int) from jsonb_array_elements_text(r->'parcelas') x), '{}'),
            nullif(r->>'referencia',''), nullif(r->>'descricao',''), nullif(r->>'comprador',''),
            nullif(r->>'vencimento','')::date, nullif(r->>'data_credito','')::date,
            coalesce((r->>'honorario')::numeric,0), (r->>'valor')::numeric);
  end loop;
  return v_id;
end $$;

-- corrige um contrato com os dados do arquivo (só os campos enviados)
create or replace function public.rcb_corrigir_contrato(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_l bigint; v_c bigint; r jsonb; n int := 0;
begin
  if not public.is_admin() then raise exception 'Sem permissão'; end if;
  if not exists (select 1 from rcb_contratos where id = p_id) then raise exception 'Contrato % não cadastrado.', p_id; end if;
  if p ? 'leilao' then
    select id into v_l from rcb_leiloes where nome = p#>>'{leilao,nome}' and data is not distinct from nullif(p#>>'{leilao,data}','')::date;
    if v_l is null then
      insert into rcb_leiloes (nome, data) values (p#>>'{leilao,nome}', nullif(p#>>'{leilao,data}','')::date) returning id into v_l;
    end if;
    update rcb_contratos set leilao_id = v_l where id = p_id; n := n + 1;
  end if;
  if p ? 'contrato' then
    update rcb_contratos set
      animal = case when p->'contrato' ? 'animal' then nullif(p#>>'{contrato,animal}','') else animal end,
      lote = case when p->'contrato' ? 'lote' then nullif(p#>>'{contrato,lote}','') else lote end,
      percentual = case when p->'contrato' ? 'percentual' then nullif(p#>>'{contrato,percentual}','')::numeric else percentual end,
      valor_total = coalesce(nullif(p#>>'{contrato,valor_total}','')::numeric, valor_total),
      data_contrato = coalesce(nullif(p#>>'{contrato,data_contrato}','')::date, data_contrato),
      qtd_parcelas = coalesce(nullif(p#>>'{contrato,qtd_parcelas}','')::int, qtd_parcelas)
    where id = p_id;
    n := n + 1;
  end if;
  if p ? 'comprador' then
    select comprador_id into v_c from rcb_contratos where id = p_id;
    update rcb_compradores set
      nome = coalesce(nullif(p#>>'{comprador,nome}',''), nome),
      documento = case when p->'comprador' ? 'documento' then nullif(regexp_replace(p#>>'{comprador,documento}', '\D', '', 'g'), '') else documento end
    where id = v_c;
    n := n + 1;
  end if;
  for r in select value from jsonb_array_elements(coalesce(p->'parcelas','[]'::jsonb)) loop
    if exists (select 1 from rcb_parcelas where contrato_id = p_id and numero = (r->>'numero')::int) then
      update rcb_parcelas set valor_previsto = coalesce(nullif(r->>'valor_previsto','')::numeric, valor_previsto),
                              vencimento = coalesce(nullif(r->>'vencimento','')::date, vencimento)
       where contrato_id = p_id and numero = (r->>'numero')::int;
    else
      insert into rcb_parcelas (contrato_id, numero, vencimento, valor_previsto, status_origem, tipo)
      values (p_id, (r->>'numero')::int, (r->>'vencimento')::date, (r->>'valor_previsto')::numeric, 'Incluída pela comparação de contratos',
              public.rcb_tipo_parcela((r->>'numero')::int, false, null, null));
    end if;
    n := n + 1;
  end loop;
  perform public.rcb_conferir_contrato(p_id);
  return jsonb_build_object('alteracoes', n);
end $$;

do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.proname like 'rcb\_%' loop
    execute format('revoke execute on function %s from anon, public;', f.sig);
    execute format('grant execute on function %s to authenticated;', f.sig);
  end loop;
end $$;
