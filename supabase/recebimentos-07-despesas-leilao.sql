create table if not exists public.rcb_despesas_leilao (
  id bigint generated by default as identity primary key,
  leilao_id bigint not null references public.rcb_leiloes(id),
  contrato_id bigint references public.rcb_contratos(id),
  lote text,
  tipo text not null check (tipo in ('comissao_venda','taxa','defesa','outra')),
  descricao text not null,
  valor numeric(14,2) not null check (valor >= 0),
  percentual numeric(7,4),
  arquivo_nome text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
-- o mesmo lançamento não entra duas vezes (reenvio do mesmo Mapa de Venda)
create unique index if not exists rcb_despesas_leilao_unq on public.rcb_despesas_leilao (leilao_id, tipo, descricao, (coalesce(lote, '')), valor);

alter table public.rcb_despesas_leilao enable row level security;
drop policy if exists rcb_despesas_leilao_sel on public.rcb_despesas_leilao;
create policy rcb_despesas_leilao_sel on public.rcb_despesas_leilao for select to authenticated using (public.is_aprovado());
revoke all on public.rcb_despesas_leilao from anon;
revoke insert, update, delete on public.rcb_despesas_leilao from authenticated;
drop trigger if exists rcb_despesas_leilao_audit on public.rcb_despesas_leilao;
create trigger rcb_despesas_leilao_audit after insert or update or delete on public.rcb_despesas_leilao for each row execute function public.rcb_tg_audit();
drop trigger if exists rcb_despesas_leilao_nodel on public.rcb_despesas_leilao;
create trigger rcb_despesas_leilao_nodel before delete on public.rcb_despesas_leilao for each row execute function public.rcb_tg_bloquear_exclusao();

-- p = { leilao_id?, leilao: {nome, data, local}, arquivo, itens: [{tipo, descricao, valor, percentual?, lote?, contrato_id?}] }
-- devolve quantas despesas novas foram gravadas
create or replace function public.rcb_registrar_despesas(p jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare v_l bigint; r jsonb; n int := 0; v_novo boolean;
begin
  if not public.is_admin() then raise exception 'Sem permissão'; end if;
  v_l := nullif(p->>'leilao_id','')::bigint;
  if v_l is null then
    select id into v_l from rcb_leiloes
     where lower(nome) = lower(p#>>'{leilao,nome}') and data is not distinct from nullif(p#>>'{leilao,data}','')::date
     order by id limit 1;
  end if;
  if v_l is null then
    if coalesce(p#>>'{leilao,nome}','') = '' then raise exception 'Leilão não informado.'; end if;
    insert into rcb_leiloes (nome, data, local) values (p#>>'{leilao,nome}', nullif(p#>>'{leilao,data}','')::date, nullif(p#>>'{leilao,local}',''))
    returning id into v_l;
  end if;
  for r in select value from jsonb_array_elements(coalesce(p->'itens','[]'::jsonb)) loop
    if coalesce((r->>'valor')::numeric, 0) <= 0 then continue; end if;
    insert into rcb_despesas_leilao (leilao_id, contrato_id, lote, tipo, descricao, valor, percentual, arquivo_nome)
    values (v_l, nullif(r->>'contrato_id','')::bigint, nullif(r->>'lote',''), coalesce(nullif(r->>'tipo',''),'outra'), coalesce(nullif(r->>'descricao',''),'Despesa'),
            (r->>'valor')::numeric, nullif(r->>'percentual','')::numeric, nullif(p->>'arquivo',''))
    on conflict (leilao_id, tipo, descricao, (coalesce(lote, '')), valor)
      do update set contrato_id = coalesce(rcb_despesas_leilao.contrato_id, excluded.contrato_id)
    returning (xmax = 0) into v_novo;
    if v_novo then n := n + 1; end if;
  end loop;
  return n;
end $$;

do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.proname like 'rcb\_%' loop
    execute format('revoke execute on function %s from anon, public;', f.sig);
    execute format('grant execute on function %s to authenticated;', f.sig);
  end loop;
end $$;
